PUBLISHED_BN = "২৬ নভেম্বর ২০২৬"


def load_pharmacies():
    """Return the pharmacy list from the single source of truth."""
    data = json.loads((ROOT / "data" / "pharmacies.json").read_text(encoding="utf-8"))
    return data["pharmacies"]


def escape(text):
    return html.escape(text, quote=True)


def bangla_digits(text):
    """Convert Latin digits to Bangla digits for display."""
    return str(text).translate(str.maketrans("0123456789", "০১২৩৪৫৬৭৮৯"))


def hours_line(pharmacy):
    """One honest hours line for a pharmacy, from its data only."""
    if pharmacy.get("hours24"):
        return "২৪ ঘণ্টা খোলা"
    if pharmacy.get("hoursText"):
        line = pharmacy["hoursText"]
        # Friday-closed entries say so in the list, so nobody travels
        # on a Friday to a shut door.
        if pharmacy.get("hoursByDay") and pharmacy["hoursByDay"].get("fri") is None:
            line += " — শুক্রবার বন্ধ"
        if pharmacy.get("breaks"):
            line += " — দুপুর ২টা–৪টা বিরতি"
        return line
    return "সময় নিশ্চিত নয় — যাওয়ার আগে ফোন করে নিন"


def phone_line(pharmacy):
    """Phone line: verified, unverified, or honestly absent."""
    phone = pharmacy.get("phone")
    if not phone:
        return '<span class="blog-no-phone">ফোন নম্বর তালিকায় নেই</span>'
    display = escape(pharmacy.get("phoneDisplay") or phone)
    link = f'<a href="tel:{escape(phone)}">{display}</a>'
    if not pharmacy.get("phoneVerified"):
        link += ' <span class="badge-unverified">অযাচাইকৃত নম্বর</span>'
    return link


def pharmacy_list_html(pharmacies, note=None):
    """Render a <ul> of pharmacies, all facts from pharmacies.json."""
    items = []
    for pharmacy in pharmacies:
        items.append(
            "      <li class=\"blog-pharm\">\n"
            f"        <strong>{escape(pharmacy['name'])}</strong>\n"
            f"        <span class=\"blog-address\">{escape(pharmacy['address'])}</span>\n"
            f"        <span class=\"blog-hours\">{escape(hours_line(pharmacy))}</span>\n"
            f"        <span class=\"blog-phone\">{phone_line(pharmacy)}</span>\n"
            "      </li>"
        )
    note_html = f"\n    <p class=\"blog-list-note\">{escape(note)}</p>" if note else ""
    return (
        "    <ul class=\"blog-pharm-list\">\n" + "\n".join(items) + "\n    </ul>" + note_html
    )


def is_late_night(pharmacy):
    """Open past midnight: 24h, or closes after midnight (close < open)."""
    if pharmacy.get("hours24"):
        return True
    open_time = pharmacy.get("open")
    close_time = pharmacy.get("close")
    if not open_time or not close_time:
        return False
    return close_time < open_time  # e.g. 07:00–03:00 crosses midnight


def word_count(text):
    """Rough word count of visible Bangla prose (tags stripped)."""
    plain = re.sub(r"<[^>]+>", " ", text)
    plain = re.sub(r"\s+", " ", plain).strip()
    return len(plain.split(" ")) if plain else 0


def reading_minutes(body_html):
    """Reading time at ~180 words/minute, minimum 3 minutes."""
    return max(3, math.ceil(word_count(body_html) / 180))

