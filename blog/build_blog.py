#!/usr/bin/env python3
"""Build the RaatPharmacy blog/guides section from data/pharmacies.json.

WHY a build script instead of hand-written pages: every pharmacy name,
phone, address and opening-hours line in the articles is rendered from
pharmacies.json — the same file the finder app uses. If the data is
corrected later, re-running this script updates every article, so an
article can never show a phone or hours that disagree with the app.
Nothing is invented here: an entry with no verified hours is shown as
"সময় নিশ্চিত নয়", an unverified phone is labelled "অযাচাইকৃত", and an
entry with no phone shows no phone at all.

Usage: python3 blog/build_blog.py   (run from the repo root)
Outputs: blog/index.html, blog/<slug>.html, sitemap.xml, robots.txt
"""
