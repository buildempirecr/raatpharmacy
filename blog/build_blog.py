def article_json_ld(article, canonical):
    """Article + breadcrumb structured data for Google."""
    breadcrumb_items = ",\n".join(
        [
            '{"@type": "ListItem", "position": 1, "name": "RaatPharmacy", '
            f'"item": "{SITE_URL}/"}}',
            '{"@type": "ListItem", "position": 2, "name": "গাইড", '
            f'"item": "{SITE_URL}/blog/"}}',
            '{"@type": "ListItem", "position": 3, "name": "'
            + escape(article["h1"])
            + '", '
            f'"item": "{canonical}"}}',
        ]
    )
    return f"""  <script type="application/ld+json">
{{
  "@context": "https://schema.org",
  "@type": "Article",
  "headline": "{escape(article["h1"])}",
  "description": "{escape(article["description"])}",
  "image": "{OG_IMAGE}",
  "author": {{"@type": "Organization", "name": "RaatPharmacy", "url": "{SITE_URL}/"}},
  "publisher": {{"@type": "Organization", "name": "RaatPharmacy", "url": "{SITE_URL}/"}},
  "datePublished": "{PUBLISHED}",
  "dateModified": "{PUBLISHED}",
  "inLanguage": "bn",
  "mainEntityOfPage": {{"@type": "WebPage", "@id": "{canonical}"}}
}}
  </script>
  <script type="application/ld+json">
{{
  "@context": "https://schema.org",
  "@type": "BreadcrumbList",
  "itemListElement": [{breadcrumb_items}]
}}
  </script>
"""


