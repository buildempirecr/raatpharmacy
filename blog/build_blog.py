def _area_list(pharmacies, areas):
    """Pharmacies in the given areas, sorted by name."""
    selected = [p for p in pharmacies if p.get("area") in areas]
    return sorted(selected, key=lambda p: p["name"])


def _by_name(pharmacies):
    return sorted(pharmacies, key=lambda p: p["name"])


